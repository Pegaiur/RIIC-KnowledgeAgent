/** 构建完整规则段文本（完全静态，无动态字段；供 system prompt 置顶注入） */
export function buildRulesPrefix(): string {
  const mustLines = MUST_RULES.map((rule, i) => `${i + 1}. ${rule}`)
  const guideLines = QUERY_GUIDES.map((guide, i) => `${i + 1}. ${guide}`)
  return [
    '【必须遵守】（硬约束，置顶）',
    `⚠ 检索词引导版本 v${RULES_VERSION}；与检索结果冲突时以检索到的语料原文为准。`,
    ...mustLines,
    '',
    `【检索词引导 v${RULES_VERSION}】（为 rag_search/grep_search 构造能命中的 query；仅命中引导、不作来源，答案须回指语料原文 file#小节）`,
    ...guideLines,
  ].join('\n')
}
